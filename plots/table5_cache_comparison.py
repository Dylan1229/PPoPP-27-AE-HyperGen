"""Table 5: HyperGen's cache against TeaCache (ported onto the same tiles), on CogVideoX at 2K on one
GPU. All cells share one prompt, one seed and one Stage-1 sketch, so the cache policy is the only
variable. Each method is shown at two thresholds: a conservative ("slow") and an aggressive ("fast")
one. Speedup and retention are against the no-cache run.

Reads T2_baselines/{timings,quality}.tsv and writes tables/table5_cache_comparison.tex.

    RESULTS_DIR=results/paper python plots/table5_cache_comparison.py
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
from _paths import RES, TABLES, FIGS, PREV  # noqa: E402  (RESULTS_DIR / OUT_DIR)
OUT = TABLES / "table5_cache_comparison.tex"
QUAL = RES / "T2_baselines/quality.tsv"
TIME = RES / "T2_baselines/timings.tsv"

LABEL = {"ours": r"\Mname{}", "teacache": "TeaCache", "adacache": "AdaCache"}
# Methods shown, in this order (--with-adacache adds AdaCache).
ORDER = ["ours", "teacache"]

# Two operating points per method: "slow" is the conservative threshold (skips less, retains more),
# "fast" the aggressive one. Other measured thresholds stay in the TSV but are not shown.
KEEP = {("ours", "0.15"): "slow", ("ours", "0.20"): "fast",
        ("teacache", "0.10"): "slow", ("teacache", "0.20"): "fast"}

# The caption (set here because the .tex is generated).
CAPTION = (
    r"Cache mechanisms on CogVideoX at 2K, single GPU, at each method's own conservative "
    r"(\emph{slow}) and aggressive (\emph{fast}) operating point. Latency is the second stage only; "
    r"speedup and retention are against the no-cache run of the same pipeline and seed. Ordered by "
    r"LPIPS."
)


def load():
    if not QUAL.exists():
        sys.exit(f"ERROR: {QUAL} not found -- run scripts/run_table5.sh")
    rows = []
    with open(QUAL) as f:
        for r in csv.DictReader(f, delimiter="\t"):
            if not (r.get("psnr") and r.get("stage2_s")):
                continue
            rows.append(r)
    return rows


def baseline_stage2():
    with open(TIME) as f:
        for r in csv.DictReader(f, delimiter="\t"):
            if r["method"] == "nocache" and r["rc"] == "0":
                return r["stage2_s"]
    return None


def fmt(v, spec, dash="--"):
    try:
        return format(float(v), spec)
    except (TypeError, ValueError):
        return dash


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--with-adacache", action="store_true",
                    help="include the AdaCache row (skip 0.0%%, i.e. it never fires here)")
    a = ap.parse_args()

    rows = load()
    order = ORDER + (["adacache"] if a.with_adacache else [])
    rows = [r for r in rows if r["method"] in order]
    # Keep only the named operating points. AdaCache has no entry in KEEP, so --with-adacache keeps
    # whatever thresholds it has.
    rows = [r for r in rows
            if (r["method"], r["thresh"]) in KEEP or r["method"] == "adacache"]
    if not rows:
        sys.exit("ERROR: no scored rows for the selected methods")
    # LPIPS ascending: best retention first, so the frontier is legible without re-sorting.
    rows.sort(key=lambda r: float(r["lpips"]))

    base = baseline_stage2()
    body = [f"Original & {fmt(base, '.0f')} & -- & -- & -- & -- \\\\", r"\hline"]
    for r in rows:
        # Named, not numbered: the raw threshold means nothing across methods (the two gates compare
        # different quantities), while slow/fast names what the reader actually chooses between.
        name = KEEP.get((r["method"], r["thresh"]), r["thresh"])
        body.append(
            f"{LABEL[r['method']]}-{name} & "
            f"{fmt(r['stage2_s'], '.0f')} & {fmt(r['speedup'], '.2f')}$\\times$ & "
            f"{fmt(r['psnr'], '.2f')} & {fmt(r['ssim'], '.3f')} & {fmt(r['lpips'], '.3f')} \\\\")

    tex = "\n".join([
        r"%% GENERATED by plots/table5_cache_comparison.py from",
        r"%%   results/T2_baselines/{timings,quality}.tsv",
        r"%% Re-run the generator rather than editing.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{" + CAPTION + r"}",
        r"\label{tab:cache speedup comparison}",
        r"\resizebox{\linewidth}{!}{",
        r"\begin{tabular}{l|cc|ccc}",
        r"\toprule",
        r"\multirow{2}{*}{Settings} & \multicolumn{2}{c|}{Stage-2 Efficiency}"
        r" & \multicolumn{3}{c}{Visual Retention} \\",
        r" & Latency (s)$\downarrow$ & Speedup$\uparrow$ & PSNR$\uparrow$ & SSIM$\uparrow$ "
        r"& LPIPS$\downarrow$ \\ \hline",
        *body,
        r"\bottomrule",
        r"\end{tabular}",
        r"}",
        r"\end{table}",
        "",
    ])
    Path(a.out).write_text(tex)
    print(f"wrote {a.out}")
    print(f"{len(rows)} rows, no-cache reference {base}s")

    # The speed/quality frontier, on stderr.
    print("\nPareto check (lower is better on both axes):", file=sys.stderr)
    for r in rows:
        s2, lp = float(r["stage2_s"]), float(r["lpips"])
        dom = [o for o in rows if o is not r and float(o["stage2_s"]) <= s2
               and float(o["lpips"]) <= lp
               and (float(o["stage2_s"]) < s2 or float(o["lpips"]) < lp)]
        tag = f"dominated by {dom[0]['method']}-{dom[0]['thresh']}" if dom else "PARETO"
        print(f"  {r['method']:<9} {r['thresh']:<6} {s2:7.1f}s  LPIPS {lp:.3f}  {tag}", file=sys.stderr)


if __name__ == "__main__":
    main()
